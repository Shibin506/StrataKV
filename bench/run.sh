#!/usr/bin/env bash
# Runs every engine RUNS times (interleaved, so a slow moment on the machine hits all engines alike) and
# writes the Markdown report to bench/results/report.md.
#
#   bench/run.sh                    # 1,000,000 keys, 3 runs
#   N=200000 RUNS=1 bench/run.sh    # quick check
set -euo pipefail
cd "$(dirname "$0")/.."
N=${N:-1000000}
RUNS=${RUNS:-3}
ENGINES=${ENGINES:-"stratakv rocksdb sqlite"}
DIR=${BENCH_DIR:-$(mktemp -d)}     # put it on the disk you want to measure
OUT=bench/results
# Built for this machine's CPU: RocksDB only uses SSE4.2 / AVX2 / PCLMUL (fast CRC32C checksums, among others)
# when Rust is told the CPU has them, and a baseline x86-64 build would handicap it. Its own target directory,
# so the normal debug and test builds are not invalidated.
export RUSTFLAGS="-C target-cpu=native"
export CARGO_TARGET_DIR=target/bench-native
cargo build --release -q -p stratakv-bench
BIN=$CARGO_TARGET_DIR/release/stratakv-bench
rm -f "$OUT"/*.json
mkdir -p "$OUT"
for run in $(seq 1 "$RUNS"); do
  for engine in $ENGINES; do
    "$BIN" run --engine "$engine" --dir "$DIR/$engine" --n "$N" --out "$OUT/$engine-$run.json"
  done
done
{
  echo "<!-- generated by bench/run.sh on $(date -u +%Y-%m-%d); $(uname -sr); $(nproc) CPUs; $(grep -m1 "model name" /proc/cpuinfo | cut -d: -f2 | xargs) -->"
  "$BIN" report "$OUT"/*.json
} > "$OUT/report.md"
cat "$OUT/report.md"
